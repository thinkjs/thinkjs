'use strict';

const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const HEADER = '// Generated by think-ts-helper. Do not edit.\n';
const OWNER = 'think-ts-helper';
const slash = value => value.split(path.sep).join('/');
const sorted = values => values.sort();

function directory(file) {
  try { return fs.statSync(file).isDirectory(); } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
}

function fail(code, message) {
  const error = new Error(`${code}: ${message}`);
  error.code = code;
  throw error;
}

function assertUnique(names, description) {
  const seen = new Map();
  for (const name of names) {
    const key = name.toLowerCase();
    if (seen.has(key)) fail('SERVICE_COLLISION', `${description}: ${seen.get(key)} and ${name}`);
    seen.set(key, name);
  }
}

function scan(dir, root) {
  const found = [];
  if (!directory(dir)) return found;
  if (fs.lstatSync(dir).isSymbolicLink()) fail('UNSUPPORTED_SYMLINK', dir);
  function walk(current) {
    for (const entry of fs.readdirSync(current, {withFileTypes: true}).sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
      const file = path.join(current, entry.name);
      if (entry.isSymbolicLink()) fail('UNSUPPORTED_SYMLINK', slash(path.relative(root, file)));
      if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
      if (entry.isDirectory()) walk(file);
      else if (/\.(?:ts|js)$/.test(entry.name) && !/\.d\.ts$/.test(entry.name)) {
        found.push({name: slash(path.relative(dir, file)).replace(/\.(ts|js)$/, ''), file: slash(path.relative(root, file))});
      }
    }
  }
  walk(dir);
  assertUnique(found.map(item => item.name), `service directory ${slash(path.relative(root, dir))}`);
  return found;
}

function record(items) {
  return Object.fromEntries(items.map(item => [item.name, item.file]));
}

// Inspect syntax only. Never require or evaluate an application module.
function exportSelector(file) {
  const source = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
  const unsupported = reason => fail('UNSUPPORTED_EXPORT', `${file}: ${reason}`);
  if (source.parseDiagnostics.length) unsupported('source cannot be parsed by TypeScript 3.9');
  let esDefault = false;
  let exportEquals = false;
  let commonJs = false;
  let named = false;
  function access(node) {
    if (ts.isIdentifier(node)) return node.text;
    if (ts.isPropertyAccessExpression(node)) return access(node.expression) + '.' + node.name.text;
    if (ts.isElementAccessExpression(node) && node.argumentExpression && ts.isStringLiteral(node.argumentExpression)) return access(node.expression) + '.' + node.argumentExpression.text;
    return '';
  }
  function inspect(node) {
    if ((ts.isIdentifier(node) || ts.isStringLiteral(node)) && node.text === '__esModule') unsupported('__esModule interop is not supported; use a source-level default export');
    if (ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.EqualsToken) {
      const target = access(node.left);
      if (target === 'module.exports' || target.startsWith('module.exports.') || target.startsWith('exports.')) {
        if (!ts.isExpressionStatement(node.parent) || node.parent.parent !== source) unsupported('conditional or nested CommonJS export assignment');
        commonJs = true;
      }
    }
    ts.forEachChild(node, inspect);
  }
  for (const statement of source.statements) {
    if (ts.isExportAssignment(statement)) {
      if (statement.isExportEquals) exportEquals = true;
      else esDefault = true;
    }
    const modifiers = statement.modifiers || [];
    if (modifiers.some(modifier => modifier.kind === ts.SyntaxKind.DefaultKeyword)) esDefault = true;
    if (modifiers.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)) named = true;
    if (ts.isExportDeclaration(statement)) unsupported('export lists/re-exports are not supported; use an explicit default or export assignment');
  }
  inspect(source);
  if (Number(esDefault) + Number(exportEquals) + Number(commonJs) !== 1) unsupported('expected one explicit default, export =, or CommonJS export style');
  if (named && !esDefault) unsupported('named-only or mixed exports are not supported');
  return esDefault ? '.default' : '';
}

function safeOutput(source, output) {
  const relative = path.relative(source, output);
  if (!relative || (!relative.startsWith('..' + path.sep) && relative !== '..' && !path.isAbsolute(relative))) fail('UNSAFE_OUTPUT', 'output must not be inside the source directory');
  let current = output;
  while (true) {
    try {
      if (fs.lstatSync(current).isSymbolicLink()) fail('UNSAFE_OUTPUT', `symlink output ancestor: ${current}`);
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
    const parent = path.dirname(current);
    if (parent === current) break;
    current = parent;
  }
}

function render(options = {}) {
  const root = path.resolve(options.root || process.cwd());
  const source = path.resolve(root, options.sourceDir || 'src');
  const output = path.resolve(root, options.outDir || '.thinkjs/types');
  if (!directory(source)) fail('SOURCE_NOT_FOUND', source);
  safeOutput(source, output);
  // This is the loader's layout signal, not a heuristic based on service files.
  const multi = directory(path.join(source, 'common/config'));
  const moduleNames = multi ? sorted(fs.readdirSync(source).filter(name => directory(path.join(source, name)))) : ['__single__'];
  assertUnique(moduleNames, 'module directories');
  if (multi && moduleNames.includes('__single__')) fail('RESERVED_MODULE', '__single__ is reserved for single-module applications');
  const discovered = {};
  for (const name of moduleNames) {
    const base = multi ? path.join(source, name) : source;
    if (fs.lstatSync(base).isSymbolicLink()) fail('UNSUPPORTED_SYMLINK', base);
    Object.defineProperty(discovered, name, {value: record(scan(path.join(base, 'service'), root)), enumerable: true});
  }
  const modules = {};
  for (const name of moduleNames) {
    const effective = {...(multi ? discovered.common : {}), ...discovered[name]};
    assertUnique(Object.keys(effective), `effective module ${name}`);
    Object.defineProperty(modules, name, {value: Object.fromEntries(sorted(Object.keys(effective)).map(key => [key, effective[key]])), enumerable: true});
  }
  const selectors = new Map();
  const lines = [HEADER.trimEnd(), "import 'thinkjs/service-types';", '', "declare module 'thinkjs/service-types' {", '  interface ServiceModules {'];
  for (const name of moduleNames) {
    lines.push(`    ${JSON.stringify(name)}: {`);
    for (const [service, file] of Object.entries(modules[name])) {
      let ref = slash(path.relative(output, path.resolve(root, file))).replace(/\.(ts|js)$/, '');
      if (!ref.startsWith('.')) ref = './' + ref;
      if (!selectors.has(file)) selectors.set(file, exportSelector(path.resolve(root, file)));
      lines.push(`      ${JSON.stringify(service)}: typeof import(${JSON.stringify(ref)})${selectors.get(file)};`);
    }
    lines.push('    };');
  }
  lines.push('  }', '}', '');
  const manifest = {generator: OWNER, version: 1, layout: multi ? 'multi' : 'single', sourceDir: slash(path.relative(root, source)), modules};
  const files = {
    'service.d.ts': lines.join('\n'),
    'index.d.ts': HEADER + "import './service';\n" +
      "import { ThinkServices, ContextServices, ControllerServices } from 'thinkjs/service-types';\n" +
      "export * from 'thinkjs/service-types';\n" +
      `export type AppThink<T> = ThinkServices<T, '${manifest.layout}'>;\n` +
      `export type AppContext<T> = ContextServices<T, '${manifest.layout}'>;\n` +
      `export type AppController<T, M extends string = string> = ControllerServices<T, '${manifest.layout}', M>;\n`,
    'manifest.json': JSON.stringify(manifest, null, 2) + '\n'
  };
  return {root, output, files, manifest};
}

function owned(name, content) {
  if (name !== 'manifest.json') return content.startsWith(HEADER);
  try { return JSON.parse(content).generator === OWNER; } catch { return false; }
}

function generate(options = {}) {
  const result = render(options);
  const changed = [];
  // Validate every destination before writing any output.
  for (const [name, content] of Object.entries(result.files)) {
    const file = path.join(result.output, name);
    let previous;
    try {
      if (fs.lstatSync(file).isSymbolicLink()) fail('UNSAFE_OUTPUT', file);
      previous = fs.readFileSync(file, 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (previous !== undefined && !owned(name, previous)) fail('UNOWNED_OUTPUT', `Refusing to overwrite ${file}`);
    if (previous !== content) changed.push(name);
  }
  if (!options.check && changed.length) {
    fs.mkdirSync(result.output, {recursive: true});
    for (const name of changed) {
      const target = path.join(result.output, name);
      const temporary = path.join(result.output, `.${name}.${process.pid}.${require('node:crypto').randomBytes(8).toString('hex')}.tmp`);
      try {
        fs.writeFileSync(temporary, result.files[name], {flag: 'wx'});
        fs.renameSync(temporary, target);
      } finally {
        fs.rmSync(temporary, {force: true});
      }
    }
  }
  return {...result, changed};
}

module.exports = {generate};
